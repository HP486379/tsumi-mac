import { chromium } from '@playwright/test';
import { mkdir,writeFile } from 'node:fs/promises';
import path from 'node:path';
const out=path.resolve(process.env.MINI_OUTPUT||'test-results/mini-reference');await mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH});
const page=await browser.newPage({viewport:{width:1280,height:1050},deviceScaleFactor:2});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:4173/tools/mini/view.html');await page.waitForFunction(()=>!!window.miniReference);
const data=await page.evaluate(()=>window.miniReference);
if(data.currentContacts.maxSurfaceGap>1e-9||data.currentContacts.maxGroundGap>1e-9)throw Error('Current contact mapping changed');
for(const row of data.audit)for(const axis of ['w','h','d'])if(Math.abs(row.measured[axis]-row.mm[axis])>1e-9)throw Error('Reference mesh distorted');
await page.locator('.current').screenshot({path:path.join(out,'before-current.png')});
await page.locator('.reference').screenshot({path:path.join(out,'after-reference-prototype.png')});
await page.screenshot({path:path.join(out,'comparison.png'),fullPage:true});
await page.goto('http://127.0.0.1:4173/?seed=20261028');await page.getByTestId('start-button').click();await page.waitForFunction(()=>window.__tsumimac?.views().synchronized);await page.keyboard.press('KeyP');
data.game=await page.evaluate(()=>{const v=window.__tsumimac.views();return {synchronized:v.synchronized,sameObject:v.front===v.oblique,items:v.front.items};});
if(!data.game.sameObject)throw Error('Game synchronization changed');
await page.addStyleTag({content:'[data-testid="pause-overlay"]{visibility:hidden!important}'});await page.screenshot({path:path.join(out,'game-unchanged.png')});
if(errors.length)throw Error(errors.join('\n'));data.errors=errors;
await writeFile(path.join(out,'measurements.json'),JSON.stringify(data,null,2));
console.log(JSON.stringify({dimensions:data.audit,ratio:data.ratio,currentContactError:data.currentContacts.maxSurfaceGap,errors}));await browser.close();
